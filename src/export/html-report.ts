/**
 * HTML report export — standalone single-file HTML with embedded SVG,
 * call metadata, findings, and message details.
 */

import type { Call } from '../model/types.js';
import { buildMarkdown } from './markdown.js';
import { formatTime, formatRelativeTime } from '../parser/timestamp.js';
import { downloadBlob } from './svg.js';

export function exportHtmlReport(call: Call, svgSource: string, filename: string): void {
  const html = buildHtmlReport(call, svgSource);
  const blob = new Blob([html], { type: 'text/html' });
  downloadBlob(blob, `${filename}.html`);
}

function buildHtmlReport(call: Call, svgSource: string): string {
  const from = call.callingNumber ?? 'Unknown';
  const to = call.calledNumber ?? 'Unknown';
  const time = formatTime(call.startTime);
  const dur = call.duration ? formatRelativeTime(call.duration) : 'N/A';

  let findingsHtml = '';
  if (call.findings.length > 0) {
    findingsHtml = '<h2>Findings</h2>';
    for (const f of call.findings) {
      const color = f.severity === 'error' || f.severity === 'critical' ? '#ff4757'
        : f.severity === 'warning' ? '#f5a623' : '#4f8ff7';
      findingsHtml += `<div style="border-left:3px solid ${color};padding:8px 12px;margin:8px 0;background:rgba(255,255,255,0.03)">
        <strong style="color:${color}">${esc(f.title)}</strong>
        <p style="margin:4px 0 0;color:#8b8f9a">${esc(f.description)}</p>
      </div>`;
    }
  }

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; img-src data:">
<title>Call Report — CID:${call.cid}</title>
<style>
  body { background:#0f1117; color:#e0e2e8; font-family:-apple-system,sans-serif; margin:0; padding:24px; font-size:13px; line-height:1.6; }
  h1 { font-size:18px; margin-bottom:8px; }
  h2 { font-size:14px; margin:20px 0 8px; color:#8b8f9a; text-transform:uppercase; letter-spacing:0.05em; }
  table { border-collapse:collapse; }
  th,td { padding:4px 16px 4px 0; text-align:left; }
  th { color:#8b8f9a; font-weight:500; }
  td { font-family:'SF Mono',monospace; }
  .svg-container { overflow-x:auto; margin:16px 0; background:#181a20; border-radius:6px; padding:16px; }
  .badge { display:inline-block; padding:2px 8px; border-radius:3px; font-size:11px; font-weight:500; }
  .badge-success { background:rgba(52,199,89,0.15); color:#34c759; }
  .badge-failed { background:rgba(255,71,87,0.15); color:#ff4757; }
</style>
</head>
<body>
<h1>Call Report — CID:${call.cid}</h1>
<h2>Summary</h2>
<table>
  <tr><th>Calling</th><td>${esc(from)}</td></tr>
  <tr><th>Called</th><td>${esc(to)}</td></tr>
  <tr><th>Time</th><td>${time}</td></tr>
  <tr><th>Duration</th><td>${dur}</td></tr>
  <tr><th>Status</th><td><span class="badge badge-${call.status === 'success' ? 'success' : 'failed'}">${call.status}${call.finalResponseCode ? ` (${call.finalResponseCode})` : ''}</span></td></tr>
  <tr><th>Legs</th><td>${call.legs.length}</td></tr>
</table>

${findingsHtml}

<h2>Call Ladder</h2>
<div class="svg-container">
${svgSource}
</div>

<p style="color:#5c5f6a;margin-top:24px;font-size:11px">Generated by Call Ladder — Ribbon SBC Diagnostic Viewer</p>
</body>
</html>`;
}

function esc(s: string): string {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}
