/**
 * Markdown export — human-readable troubleshooting summary.
 */

import type { Call } from '../model/types.js';
import { formatTime, formatRelativeTime } from '../parser/timestamp.js';
import { getParticipants, buildLadderEvents } from '../analysis/call.js';
import { downloadBlob } from './svg.js';

export function exportMarkdown(call: Call, filename: string): void {
  const md = buildMarkdown(call);
  const blob = new Blob([md], { type: 'text/markdown' });
  downloadBlob(blob, `${filename}.md`);
}

export function buildMarkdown(call: Call): string {
  const lines: string[] = [];
  const from = call.callingNumber ?? 'Unknown';
  const to = call.calledNumber ?? 'Unknown';
  const time = formatTime(call.startTime);
  const dur = call.duration ? formatRelativeTime(call.duration) : 'N/A';

  lines.push(`# Call Analysis — CID:${call.cid}`);
  lines.push('');
  lines.push(`| Field | Value |`);
  lines.push(`|-------|-------|`);
  lines.push(`| Calling | ${from} |`);
  lines.push(`| Called | ${to} |`);
  lines.push(`| Time | ${time} |`);
  lines.push(`| Duration | ${dur} |`);
  lines.push(`| Status | ${call.status} |`);
  if (call.finalResponseCode) {
    lines.push(`| Final Response | ${call.finalResponseCode} |`);
  }
  lines.push(`| Legs | ${call.legs.length} |`);
  lines.push('');

  // Participants
  const participants = getParticipants(call);
  lines.push('## Participants');
  lines.push('');
  for (const p of participants) {
    lines.push(`- **${p.label}**${p.addr ? ` (${p.addr})` : ''}`);
  }
  lines.push('');

  // Call flow
  lines.push('## Call Flow');
  lines.push('');
  lines.push('```');
  const events = buildLadderEvents(call);
  for (const ev of events) {
    const time = formatRelativeTime(ev.relativeTime).padStart(10);
    const dir = ev.fromCol < ev.toCol ? '--->' : '<---';
    lines.push(`${time}  ${ev.label.padEnd(20)} ${dir}`);
  }
  lines.push('```');
  lines.push('');

  // Legs detail
  for (const leg of call.legs) {
    lines.push(`## ${leg.direction.charAt(0).toUpperCase() + leg.direction.slice(1)} Leg — SG(${leg.signalingGroup})`);
    lines.push('');
    lines.push(`- Call-ID: \`${leg.callId}\``);
    if (leg.remoteLabel) lines.push(`- Remote: ${leg.remoteLabel} (${leg.remoteAddr ?? 'N/A'})`);
    lines.push(`- Messages: ${leg.messages.length}`);
    lines.push('');
  }

  // Findings
  if (call.findings.length > 0) {
    lines.push('## Findings');
    lines.push('');
    for (const f of call.findings) {
      const icon = f.severity === 'critical' || f.severity === 'error' ? '❌'
        : f.severity === 'warning' ? '⚠️' : 'ℹ️';
      lines.push(`### ${icon} ${f.title}`);
      lines.push('');
      lines.push(f.description);
      lines.push('');
    }
  }

  lines.push('---');
  lines.push('*Generated by Call Ladder — Ribbon SBC Diagnostic Viewer*');

  return lines.join('\n');
}
